import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

const root = join(import.meta.dirname, '..');
const contentDir = join(root, 'content', 'notes');
const docsDir = join(root, 'docs');
const artDir = join(docsDir, 'assets', 'art');
const slugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const generated = '<!-- Generated by npm run build. Edit content/notes/ or scripts/build.mjs. -->';
const siteName = '遊戲開發實驗簿';
const subtitle = '從一個遊戲機制開始，動手做個小實驗，再看結果是否符合預期。';
const repo = 'https://github.com/LegendaryAni/game-dev-fieldbook';

const entities = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const escapeHtml = (text) => text.replace(/[&<>"']/g, (char) => entities[char]);
const hasText = (value) => typeof value === 'string' && value.trim().length > 0;

async function readNotes() {
  const notes = [];
  for (const file of (await readdir(contentDir)).sort()) {
    if (!file.toLowerCase().endsWith('.json')) continue;

    const slug = file.slice(0, -5);
    const source = `content/notes/${file}`;
    if (!file.endsWith('.json') || !slugPattern.test(slug)) {
      throw new Error(`${source} 的檔名須採 lowercase-kebab-case.json`);
    }

    let note;
    try {
      note = JSON.parse(await readFile(join(contentDir, file), 'utf8'));
    } catch (error) {
      throw new Error(`${source} 無法讀取為 JSON。${error.message}`);
    }
    if (!note || typeof note !== 'object' || Array.isArray(note)) {
      throw new Error(`${source} 須為 JSON 物件`);
    }
    for (const field of ['title', 'summary', 'problem']) {
      if (!hasText(note[field])) throw new Error(`${source} 的 ${field} 須為非空文字`);
    }
    for (const field of ['steps', 'checks']) {
      const items = note[field];
      if (!Array.isArray(items) || items.length === 0 || !items.every(hasText)) {
        throw new Error(`${source} 的 ${field} 須至少包含一項非空文字`);
      }
    }
    notes.push({ ...note, slug });
  }
  return notes.sort((a, b) => a.title.localeCompare(b.title, 'zh-Hant-TW') || a.slug.localeCompare(b.slug));
}

